// Builds the marketing site's icons from scripts/icons-source.mjs:
//   - public/icons.svg (all icons; pages use <use href="icons.svg#i-name">)
//   - the inline copy in public/index.html (only the icons the home page uses)
// Run: npm run build:icons   ·   Check only: npm run check:icons
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { ICONS } from "./icons-source.mjs";

const PUBLIC = join(dirname(fileURLToPath(import.meta.url)), "..", "public");
const GRAD_ID = "os-icon-grad";
const FILL = `var(--icon-fill,url(#${GRAD_ID}) #5B6CFF)`;
const DETAIL = "var(--icon-detail,#fff)";
const LINE = "stroke-linecap:round;stroke-linejoin:round";
const LAYER_STYLE = {
  f: `fill:${FILL};stroke:none`,
  s: `fill:none;stroke:${FILL};stroke-width:2.2;${LINE}`,
  sw: `fill:none;stroke:${FILL};stroke-width:1.2;${LINE}`,
  d: `fill:none;stroke:${DETAIL};stroke-width:1.7;${LINE}`,
  df: `fill:${DETAIL};stroke:none`,
};
export const START = "<!-- icons:start (generated by apps/marketing/scripts/build-icons.mjs) -->";
export const END = "<!-- icons:end -->";

const GRADIENT =
  `<defs><linearGradient id="${GRAD_ID}" gradientUnits="userSpaceOnUse" x1="3" y1="21" x2="21" y2="3">` +
  `<stop offset="0" stop-color="#21D1C2"/><stop offset=".55" stop-color="#5B6CFF"/><stop offset="1" stop-color="#7B61FF"/>` +
  `</linearGradient></defs>`;

export function symbol(name) {
  const layers = ICONS[name];
  if (!layers) throw new Error(`No icon called "${name}" in icons-source.mjs`);
  const body = layers
    .map((layer) => {
      const i = layer.indexOf(":");
      const kind = layer.slice(0, i);
      if (!LAYER_STYLE[kind]) throw new Error(`Icon "${name}": unknown layer "${kind}"`);
      return `<g style="${LAYER_STYLE[kind]}">${layer.slice(i + 1)}</g>`;
    })
    .join("");
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`;
}

export function sprite(names, attrs) {
  return `<svg xmlns="http://www.w3.org/2000/svg"${attrs}>${GRADIENT}\n${names.map(symbol).join("\n")}\n</svg>`;
}

/** Icon names a page refers to, e.g. href="#i-camera" or href="icons.svg#i-camera". */
export function usedIcons(html) {
  return [...new Set([...html.matchAll(/href="(?:icons\.svg)?#i-([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();
}

export function buildIndex(html) {
  const s = html.indexOf(START);
  const e = html.indexOf(END);
  if (s < 0 || e < s) throw new Error("index.html: icon markers not found");
  // Not display:none: gradients inside a display:none <svg> do not paint in some browsers.
  const inline = sprite(usedIcons(html), ' aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden"');
  return html.slice(0, s) + START + inline + html.slice(e);
}

export function build() {
  const names = Object.keys(ICONS).sort();
  const file =
    "<!-- OpalSwift icons. Generated by apps/marketing/scripts/build-icons.mjs from icons-source.mjs. Do not edit by hand. -->\n" +
    sprite(names, "") +
    "\n";
  const indexPath = join(PUBLIC, "index.html");
  return {
    [join(PUBLIC, "icons.svg")]: file,
    [indexPath]: buildIndex(readFileSync(indexPath, "utf8")),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [path, content] of Object.entries(build())) {
    if (readFileSync(path, "utf8") === content) continue;
    if (check) {
      console.error(`Out of date: ${path}. Run npm run build:icons.`);
      stale++;
    } else {
      writeFileSync(path, content);
      console.log(`Wrote ${path}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
