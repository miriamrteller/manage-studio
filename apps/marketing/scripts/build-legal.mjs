  <div class="foot-signin" style="text-align:center;padding:14px 0 0;font-size:14px"><a href="https://app.opalswift.com" style="color:inherit;opacity:.75" data-he="כניסה לחשבון" data-en="Sign in to your account">כניסה לחשבון</a></div>
