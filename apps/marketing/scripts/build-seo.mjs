// Builds each marketing page's search and link-preview tags from scripts/seo-source.mjs:
//   - the <title> and meta tags between the seo markers in each page's <head>
//     (title and description switch language with the page; previews are English,
//     the site's default language)
//   - public/sitemap.xml (every page, legal pages included)
// public/robots.txt is a plain file that points to the sitemap.
// Run: npm run build:seo   ·   Check only: npm run check:seo
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { PAGES, SITE, SHARE_IMAGE } from "./seo-source.mjs";

const PUBLIC = join(dirname(fileURLToPath(import.meta.url)), "..", "public");
export const START = "<!-- seo:start (generated by apps/marketing/scripts/build-seo.mjs) -->";
export const END = "<!-- seo:end -->";

const attr = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const text = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** The page's address as Cloudflare Pages serves it (no .html). */
export function pageUrl(file) {
  return file === "index.html" ? `${SITE}/` : `${SITE}/${file.replace(/\.html$/, "")}`;
}

export function headBlock(file, page) {
  const { title, description } = page;
  const url = pageUrl(file);
  return [
    START,
    `<title data-en="${attr(title.en)}" data-he="${attr(title.he)}">${text(title.he)}</title>`,
    `<meta name="description" content="${attr(description.en)}" data-en-content="${attr(description.en)}" data-he-content="${attr(description.he)}"/>`,
    `<link rel="canonical" href="${url}"/>`,
    `<meta property="og:type" content="website"/>`,
    `<meta property="og:site_name" content="OpalSwift"/>`,
    `<meta property="og:title" content="${attr(title.en)}"/>`,
    `<meta property="og:description" content="${attr(description.en)}"/>`,
    `<meta property="og:url" content="${url}"/>`,
    `<meta property="og:image" content="${SITE}/${SHARE_IMAGE}"/>`,
    `<meta property="og:image:width" content="1200"/>`,
    `<meta property="og:image:height" content="630"/>`,
    `<meta property="og:locale" content="en_GB"/>`,
    `<meta property="og:locale:alternate" content="he_IL"/>`,
    `<meta name="twitter:card" content="summary_large_image"/>`,
    END,
  ].join("\n");
}

/** Puts the block in place of the markers, or of the page's first <title> the first time. */
export function applyHead(html, block) {
  const s = html.indexOf(START);
  if (s !== -1) {
    const e = html.indexOf(END, s);
    if (e === -1) throw new Error("seo:start without seo:end");
    return html.slice(0, s) + block + html.slice(e + END.length);
  }
  const m = html.match(/<title[^>]*>[\s\S]*?<\/title>/);
  if (!m) throw new Error("no <title> to replace");
  return html.replace(m[0], block);
}

export function sitemap(files) {
  const urls = files
    .slice()
    .sort((a, b) => (a === "index.html" ? -1 : b === "index.html" ? 1 : a.localeCompare(b)))
    .map((f) => `  <url><loc>${pageUrl(f)}</loc></url>`)
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

function main() {
  const check = process.argv.includes("--check");
  const htmlFiles = readdirSync(PUBLIC).filter((f) => f.endsWith(".html"));
  const outputs = new Map();
  for (const file of Object.keys(PAGES)) {
    if (!htmlFiles.includes(file)) throw new Error(`seo-source.mjs lists ${file}, which is not in public/`);
    const path = join(PUBLIC, file);
    outputs.set(path, applyHead(readFileSync(path, "utf8"), headBlock(file, PAGES[file])));
  }
  outputs.set(join(PUBLIC, "sitemap.xml"), sitemap(htmlFiles));

  const stale = [];
  for (const [path, want] of outputs) {
    let have = "";
    try { have = readFileSync(path, "utf8"); } catch {}
    if (have === want) continue;
    if (check) stale.push(path);
    else writeFileSync(path, want);
  }
  if (check && stale.length) {
    console.error(`Out of date, run npm run build:seo:\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  if (!check) console.log(`SEO tags: ${Object.keys(PAGES).length} pages, sitemap: ${htmlFiles.length} pages`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
