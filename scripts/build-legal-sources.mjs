#!/usr/bin/env node
/**
 * Copy the signed-document templates from docs/legal into packages/shared, so
 * the browser and the Edge Functions (via email-dist) fill the same text.
 * Runs as part of `pnpm email:bundle`; legal-pack.test.ts fails if it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Template ids → docs/legal file prefixes. Follow renames in docs/legal here.
const FILES = {
  'health-declaration-child': '07b-health-declaration-child',
  'health-declaration-adult': '07b-health-declaration-adult',
  'service-agreement': '07c-service-agreement',
  'addon-photographer': '07c-addon-photographer',
  'addon-beautician': '07c-addon-beautician',
  'addon-coaching': '07c-addon-coaching',
};

const sources = {};
for (const [id, prefix] of Object.entries(FILES)) {
  sources[id] = {};
  for (const lang of ['en', 'he']) {
    sources[id][lang] = readFileSync(join(root, 'docs/legal', `${prefix}.${lang}.md`), 'utf8').replace(/\r\n/g, '\n');
  }
}

const out = `/** Generated by scripts/build-legal-sources.mjs from docs/legal — do not edit. */
export const SIGNED_TEMPLATE_FILES = ${JSON.stringify(FILES, null, 2)} as const;

export const SIGNED_TEMPLATE_SOURCES: Record<keyof typeof SIGNED_TEMPLATE_FILES, Record<'en' | 'he', string>> = ${JSON.stringify(sources, null, 2)};
`;
const file = join(root, 'packages/shared/src/legal/signed-template-sources.ts');
writeFileSync(file, out, 'utf8');
console.log(`Wrote ${file}`);
