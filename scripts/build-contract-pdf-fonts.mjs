#!/usr/bin/env node
/**
 * Embed the Alef font (SIL OFL 1.1, Hebrew + Latin) into a TypeScript module
 * for the signed-contract PDF renderer. Edge Functions are deployed as a
 * bundle of modules, not a directory tree, so a sibling .ttf cannot be read at
 * runtime — the bytes travel inside the code, base64-encoded, the same way
 * the pre-rendered email shells do.
 *
 * Source files: supabase/functions/_shared/contract-pdf/fonts/*.ttf
 * Output:       supabase/functions/_shared/contract-pdf/alef-font-data.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase/functions/_shared/contract-pdf');

const faces = [
  ['ALEF_REGULAR_BASE64', 'fonts/Alef-Regular.ttf'],
  ['ALEF_BOLD_BASE64', 'fonts/Alef-Bold.ttf'],
];

let ts = `/**
 * Generated by scripts/build-contract-pdf-fonts.mjs — do not edit.
 * Alef by HaGilda & Mushon Zer-Aviv, SIL Open Font License 1.1 (see fonts/OFL.txt).
 */
`;
for (const [name, file] of faces) {
  const b64 = readFileSync(join(dir, file)).toString('base64');
  ts += `\nexport const ${name} =\n  "${b64}";\n`;
}
writeFileSync(join(dir, 'alef-font-data.ts'), ts, 'utf8');
console.log(`Wrote ${join(dir, 'alef-font-data.ts')}`);
