#!/usr/bin/env node
/**
 * Copy the in-app help guides (help.topics in apps/web/src/i18n/en.json and
 * he.json, with the kinds of business from helpTopics.ts) into supabase/functions/_shared/help-guides.ts, so the
 * assistant-chat Edge Function answers from exactly the guides the Help page
 * shows. Run after changing a guide: `node scripts/build-help-guides.mjs`.
 * apps/web/src/__tests__/assistant-help-guides.test.ts fails if it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function buildHelpGuidesSource() {
  const guides = {};
  for (const lang of ['en', 'he']) {
    const json = JSON.parse(readFileSync(join(root, 'apps/web/src/i18n', `${lang}.json`), 'utf8'));
    guides[lang] = json.help.topics;
  }
  // Which kinds of business each guide is for, from apps/web/src/features/help/helpTopics.ts.
  const topicsSource = readFileSync(join(root, 'apps/web/src/features/help/helpTopics.ts'), 'utf8');
  const verticals = {};
  for (const m of topicsSource.matchAll(/\{\s*id:\s*'([a-z_]+)',\s*verticals:\s*\[([^\]]*)\]/g)) {
    verticals[m[1]] = [...m[2].matchAll(/'([a-z-]+)'/g)].map((v) => v[1]);
  }
  return `/** Generated by scripts/build-help-guides.mjs from apps/web/src/i18n (help.topics) and helpTopics.ts — do not edit. */
export type HelpGuide = { title: string; summary: string; steps: string[] };
export const HELP_GUIDES: Record<"en" | "he", Record<string, HelpGuide>> = ${JSON.stringify(guides, null, 2)};
/** Kinds of business (tenants.skin) each guide is for. */
export const HELP_GUIDE_VERTICALS: Record<string, string[]> = ${JSON.stringify(verticals, null, 2)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(root, 'supabase/functions/_shared/help-guides.ts');
  writeFileSync(out, buildHelpGuidesSource());
  console.log(`Wrote ${out}`);
}
