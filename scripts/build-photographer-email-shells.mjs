#!/usr/bin/env node
/**
 * Pre-render the photographer automatic emails (quote_sent, booking_confirmed,
 * shoot_reminder, shoot_thank_you, gallery_ready) in Node, where React Email
 * works. Edge Functions substitute runtime values — no React in Deno.
 * Same approach as build-admin-announcement-email-shells.mjs.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'supabase/functions/_shared/photographer-email-shells');
const outFile = join(outDir, 'generated.ts');

const TEMPLATES = {
  quote_sent: ['recipientName', 'quoteUrl', 'totalFormatted', 'validUntil', 'shootDate'],
  booking_confirmed: [
    'recipientName', 'shootDate', 'totalFormatted', 'depositFormatted', 'balanceFormatted',
    'balanceDueDate', 'quoteUrl',
  ],
  shoot_reminder: ['recipientName', 'shootDate', 'shootTime', 'location'],
  shoot_thank_you: ['recipientName'],
  gallery_ready: ['recipientName', 'galleryUrl'],
};

const placeholder = (name) => `{{MS_${name.replace(/([A-Z])/g, '_$1').toUpperCase()}}}`;
const SCHOOL = '{{MS_SCHOOL_NAME}}';
const PRIMARY = '{{MS_PRIMARY_COLOR}}';
const ACCENT = '{{MS_ACCENT_COLOR}}';
const BUILD_PRIMARY = '#a1b2c3';
const BUILD_ACCENT = '#d4e5f6';

const { renderEmailTemplate } = await import(
  pathToFileURL(join(root, 'packages/shared/dist/email/render-template.js')).href,
);

const strings = {
  en: JSON.parse(readFileSync(join(root, 'packages/shared/src/i18n/email-templates-en.json'), 'utf8')),
  he: JSON.parse(readFileSync(join(root, 'packages/shared/src/i18n/email-templates-he.json'), 'utf8')),
};

async function renderShell(templateName, language) {
  const variables = Object.fromEntries(TEMPLATES[templateName].map((name) => [name, placeholder(name)]));
  const { html } = await renderEmailTemplate({
    templateName,
    language,
    schoolName: SCHOOL,
    tenantColors: { primary_color: BUILD_PRIMARY, accent_color: BUILD_ACCENT },
    variables,
    subject: 'unused',
  });
  return html
    .split(BUILD_PRIMARY).join(PRIMARY)
    .split(BUILD_ACCENT).join(ACCENT)
    .split('var(--email-primary)').join(PRIMARY)
    .split('var(--email-accent)').join(ACCENT);
}

const shells = {};
const subjects = {};
for (const templateName of Object.keys(TEMPLATES)) {
  shells[templateName] = {
    en: await renderShell(templateName, 'en'),
    he: await renderShell(templateName, 'he'),
  };
  subjects[templateName] = {
    en: strings.en[templateName].subject,
    he: strings.he[templateName].subject,
  };
}

const placeholders = Object.fromEntries(
  [...new Set(Object.values(TEMPLATES).flat())].map((name) => [name, placeholder(name)]),
);

mkdirSync(outDir, { recursive: true });

const ts = `/** Generated by scripts/build-photographer-email-shells.mjs — do not edit. */
export type PhotographerEmailLanguage = 'en' | 'he';
export type PhotographerEmailKey = ${Object.keys(TEMPLATES).map((k) => `'${k}'`).join(' | ')};

export const PHOTOGRAPHER_EMAIL_VARIABLES: Record<PhotographerEmailKey, readonly string[]> = ${JSON.stringify(TEMPLATES, null, 2)} as const;

const PLACEHOLDERS: Record<string, string> = ${JSON.stringify(placeholders, null, 2)};

/** Subject templates; only {schoolName} is interpolated. */
export const PHOTOGRAPHER_EMAIL_SUBJECTS: Record<PhotographerEmailKey, Record<PhotographerEmailLanguage, string>> = ${JSON.stringify(subjects, null, 2)};

export const PHOTOGRAPHER_EMAIL_SHELLS: Record<PhotographerEmailKey, Record<PhotographerEmailLanguage, string>> = ${JSON.stringify(shells, null, 2)};

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function applyPhotographerEmailShell(
  shell: string,
  values: {
    schoolName: string;
    primaryColor: string;
    accentColor: string;
    variables: Record<string, string>;
  },
): string {
  const replacements: Array<[string, string]> = [
    ['${SCHOOL}', escapeHtml(values.schoolName)],
    ['${PRIMARY}', escapeHtml(values.primaryColor)],
    ['${ACCENT}', escapeHtml(values.accentColor)],
    ['var(--email-text)', '#1f2937'],
    ['var(--email-neutral)', '#6b7280'],
  ];
  for (const [name, token] of Object.entries(PLACEHOLDERS)) {
    replacements.push([token, escapeHtml(values.variables[name] ?? '—')]);
  }
  let html = shell;
  for (const [token, value] of replacements) {
    html = html.split(token).join(value);
  }
  return html;
}
`;

writeFileSync(outFile, ts, 'utf8');
console.log(`Wrote ${outFile}`);
