#!/usr/bin/env node
/**
 * Pre-render auth email HTML in Node (React Email works here).
 * Edge Functions load the shells and substitute runtime values — no React in Deno.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'supabase/functions/_shared/auth-email-shells');
const outFile = join(outDir, 'generated.ts');

const PLACEHOLDER = {
  magicLinkUrl: '{{MAGIC_LINK_URL}}',
  schoolName: '{{SCHOOL_NAME}}',
  otpCode: '{{OTP_CODE}}',
  primary: '{{PRIMARY_COLOR}}',
  accent: '{{ACCENT_COLOR}}',
  brandFill: '{{BRAND_FILL}}',
  brandEnd: '{{BRAND_END}}',
};

/** Valid hex used only while rendering; replaced in output HTML. */
const BUILD_PRIMARY = '#a1b2c3';
const BUILD_ACCENT = '#d4e5f6';

/** Sentinel OTP replaced at runtime (compact display, no letter-spacing). */
const BUILD_OTP = '123456';

const { deriveEmailBrand } = await import(pathToFileURL(join(root, 'packages/shared/dist/email/brand.js')).href);
const { EMAIL_TEMPLATE_NAMES, renderEmailTemplate } = await import(
  pathToFileURL(join(root, 'packages/shared/dist/email/render-template.js')).href,
);

async function renderShell(language, withOtp) {
  const variables = {
    magicLinkUrl: PLACEHOLDER.magicLinkUrl,
    confirmationUrl: PLACEHOLDER.magicLinkUrl,
    expiresInMinutes: 15,
  };
  if (withOtp) {
    variables.otpCode = BUILD_OTP;
    variables.token = BUILD_OTP;
  }

  const { html } = await renderEmailTemplate({
    templateName: EMAIL_TEMPLATE_NAMES.MAGIC_LINK,
    language,
    schoolName: PLACEHOLDER.schoolName,
    tenantColors: {
      primary_color: BUILD_PRIMARY,
      accent_color: BUILD_ACCENT,
    },
    variables,
  });

  // Gradient surfaces (header band, button, code) use the AA-safe fill and the
  // shifted end colour; both are computed at send time (email-dist/email/brand.js)
  // from the studio's colours, so they get their own placeholders.
  const brand = deriveEmailBrand(BUILD_PRIMARY, BUILD_ACCENT);
  if (brand.fill.toLowerCase() === BUILD_PRIMARY || brand.end.toLowerCase() === BUILD_ACCENT) {
    throw new Error('Build colours must differ from the derived gradient colours');
  }

  return html
    .split(brand.fill).join(PLACEHOLDER.brandFill)
    .split(brand.end).join(PLACEHOLDER.brandEnd)
    .split(BUILD_PRIMARY).join(PLACEHOLDER.primary)
    .split(BUILD_ACCENT).join(PLACEHOLDER.accent)
    .split('var(--email-primary)').join(PLACEHOLDER.primary)
    .split('var(--email-accent)').join(PLACEHOLDER.accent);
}

/**
 * Studio-owner welcome (the "invite" action). OpalSwift's own colours are baked
 * in; the studio's name, address, the invite link and the logo URL are filled
 * in at send time.
 */
const WELCOME_PLACEHOLDER = {
  studioName: '{{STUDIO_NAME}}',
  studioUrl: '{{STUDIO_URL}}',
  inviteUrl: '{{INVITE_URL}}',
  logoUrl: '{{LOGO_URL}}',
};
const OPALSWIFT_PRIMARY = '#4A58E8';
const OPALSWIFT_ACCENT = '#21D1C2';

async function renderWelcomeShell(language) {
  const { html, subject } = await renderEmailTemplate({
    templateName: EMAIL_TEMPLATE_NAMES.STUDIO_OWNER_WELCOME,
    language,
    schoolName: WELCOME_PLACEHOLDER.studioName,
    schoolLogoUrl: WELCOME_PLACEHOLDER.logoUrl,
    tenantColors: { primary_color: OPALSWIFT_PRIMARY, accent_color: OPALSWIFT_ACCENT },
    variables: {
      studioUrl: WELCOME_PLACEHOLDER.studioUrl,
      inviteUrl: WELCOME_PLACEHOLDER.inviteUrl,
    },
  });
  let out = html;
  for (const [cssVar, hex] of [
    ['var(--email-primary)', OPALSWIFT_PRIMARY],
    ['var(--email-accent)', OPALSWIFT_ACCENT],
    ['var(--email-text)', '#1f2937'],
    ['var(--email-neutral)', '#6b7280'],
  ]) {
    out = out.split(cssVar).join(hex);
  }
  return { html: out, subject };
}

const welcomeShells = { en: await renderWelcomeShell('en'), he: await renderWelcomeShell('he') };

const shells = { en: {}, he: {} };
for (const language of ['en', 'he']) {
  shells[language].linkOnly = await renderShell(language, false);
  shells[language].withOtp = await renderShell(language, true);
}

mkdirSync(outDir, { recursive: true });

const ts = `/** Generated by scripts/build-auth-email-shells.mjs — do not edit. */
export type AuthEmailLanguage = 'en' | 'he';

const PLACEHOLDER = ${JSON.stringify(PLACEHOLDER)} as const;

const BUILD_OTP = '${BUILD_OTP}';

export const MAGIC_LINK_SHELLS: Record<
  AuthEmailLanguage,
  { linkOnly: string; withOtp: string }
> = ${JSON.stringify(shells, null, 2)} as const;

const WELCOME_PLACEHOLDER = ${JSON.stringify(WELCOME_PLACEHOLDER)} as const;

/** Subject and HTML for the studio-owner welcome; see applyStudioOwnerWelcomeShell. */
export const STUDIO_OWNER_WELCOME_SHELLS: Record<
  AuthEmailLanguage,
  { html: string; subject: string }
> = ${JSON.stringify(welcomeShells, null, 2)} as const;

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function applyMagicLinkShell(
  shell: string,
  values: {
    magicLinkUrl: string;
    schoolName: string;
    otpCode?: string;
    primaryColor: string;
    accentColor: string;
    brandFill: string;
    brandEnd: string;
  },
): string {
  let html = shell
    .split(PLACEHOLDER.magicLinkUrl).join(escapeHtml(values.magicLinkUrl))
    .split(PLACEHOLDER.schoolName).join(escapeHtml(values.schoolName))
    .split(PLACEHOLDER.brandFill).join(escapeHtml(values.brandFill))
    .split(PLACEHOLDER.brandEnd).join(escapeHtml(values.brandEnd))
    .split(PLACEHOLDER.primary).join(escapeHtml(values.primaryColor))
    .split(PLACEHOLDER.accent).join(escapeHtml(values.accentColor));

  if (values.otpCode) {
    const digits = escapeHtml(values.otpCode.replace(/\\s/g, ''));
    html = html.split(BUILD_OTP).join(digits);
  }

  for (const [cssVar, hex] of [
    ['var(--email-primary)', escapeHtml(values.primaryColor)],
    ['var(--email-accent)', escapeHtml(values.accentColor)],
    ['var(--email-text)', '#1f2937'],
    ['var(--email-neutral)', '#6b7280'],
  ]) {
    html = html.split(cssVar).join(hex);
  }

  return html;
}

export function applyStudioOwnerWelcomeShell(
  shell: { html: string; subject: string },
  values: { studioName: string; studioUrl: string; inviteUrl: string; logoUrl: string },
): { html: string; subject: string } {
  const html = shell.html
    .split(WELCOME_PLACEHOLDER.studioName).join(escapeHtml(values.studioName))
    .split(WELCOME_PLACEHOLDER.studioUrl).join(escapeHtml(values.studioUrl))
    .split(WELCOME_PLACEHOLDER.inviteUrl).join(escapeHtml(values.inviteUrl))
    .split(WELCOME_PLACEHOLDER.logoUrl).join(escapeHtml(values.logoUrl));
  // A subject is plain text, not HTML: no escaping.
  const subject = shell.subject.split(WELCOME_PLACEHOLDER.studioName).join(values.studioName);
  return { html, subject };
}
`;

writeFileSync(outFile, ts, 'utf8');
console.log(`Wrote ${outFile}`);
